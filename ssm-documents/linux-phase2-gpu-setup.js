module.exports = {
  schemaVersion: '2.2',
  description: 'Phase 2: Install NVIDIA drivers and DCV GL (GPU instances only, Ubuntu/Rocky)',
  mainSteps: [{
    action: 'aws:runShellScript',
    name: 'Phase2GpuSetup',
    inputs: {
      runCommand: [
        '#!/bin/bash',
        'set -e',
        '',
        'echo "=== Phase 2: GPU Setup ==="',
        '',
        '# Verify GPU is present',
        'if ! lspci | grep -qi nvidia; then',
        '  echo "No NVIDIA GPU detected - skipping"',
        '  exit 0',
        'fi',
        '',
        '# Check if NVIDIA drivers are already installed and working',
        'NVIDIA_INSTALLED=false',
        'if command -v nvidia-smi &>/dev/null && nvidia-smi &>/dev/null; then',
        '  NVIDIA_INSTALLED=true',
        '  echo "NVIDIA drivers already installed and functional:"',
        '  nvidia-smi --query-gpu=driver_version,name --format=csv,noheader',
        '  echo "Skipping NVIDIA driver installation"',
        'fi',
        '',
        '# Detect distro',
        'if [ -f /etc/os-release ]; then',
        '  . /etc/os-release',
        '  DISTRO=$ID',
        '  MAJOR_VERSION=$(echo "$VERSION_ID" | cut -d. -f1)',
        'else',
        '  DISTRO="unknown"',
        '  MAJOR_VERSION="8"',
        'fi',
        'echo "Detected distro: $DISTRO, major version: $MAJOR_VERSION"',
        '',
        '# Check if DCV GL is already installed',
        'DCV_GL_INSTALLED=false',
        'if rpm -q nice-dcv-gl &>/dev/null 2>&1 || dpkg -l nice-dcv-gl 2>/dev/null | grep -q "^ii"; then',
        '  DCV_GL_INSTALLED=true',
        '  echo "DCV GL already installed — skipping"',
        'fi',
        '',
        '# ========== UBUNTU ==========',
        'if [ "$DISTRO" = "ubuntu" ]; then',
        '  export DEBIAN_FRONTEND=noninteractive',
        '',
        '  if [ "$NVIDIA_INSTALLED" = "false" ]; then',
        '    echo "Installing kernel headers..."',
        '    sudo apt-get install -y linux-headers-$(uname -r)',
        '',
        '    echo "Blacklisting nouveau driver..."',
        '    echo "blacklist nouveau" | sudo tee /etc/modprobe.d/blacklist-nouveau.conf',
        '    echo "options nouveau modeset=0" | sudo tee -a /etc/modprobe.d/blacklist-nouveau.conf',
        '    sudo update-initramfs -u',
        '',
        '    echo "Detecting latest available NVIDIA server driver..."',
        '    sudo apt-get update -y',
        '    NVIDIA_PKG=$(apt-cache search "^nvidia-driver-[0-9]+-server$" | sort -t- -k3 -n | tail -1 | awk "{print \\$1}")',
        '    NVIDIA_UTILS=$(echo "$NVIDIA_PKG" | sed "s/nvidia-driver/nvidia-utils/")',
        '    if [ -z "$NVIDIA_PKG" ]; then',
        '      echo "WARNING: Could not detect latest NVIDIA driver, falling back to nvidia-driver-535-server"',
        '      NVIDIA_PKG="nvidia-driver-535-server"',
        '      NVIDIA_UTILS="nvidia-utils-535-server"',
        '    fi',
        '    echo "Installing NVIDIA drivers: $NVIDIA_PKG + $NVIDIA_UTILS"',
        '    sudo apt-get install -y "$NVIDIA_PKG" "$NVIDIA_UTILS"',
        '  fi',
        '',
        '  if [ "$DCV_GL_INSTALLED" = "false" ]; then',
        '    echo "Installing DCV GL..."',
        '    cd /tmp/nice-dcv-*-ubuntu2204-x86_64 2>/dev/null || cd /tmp',
        '    if [ -f nice-dcv-gl_*.deb ]; then',
        '      sudo apt-get install -y ./nice-dcv-gl_*.deb || echo "DCV GL install warning"',
        '    else',
        '      wget -q https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-ubuntu2204-x86_64.tgz',
        '      tar -xzf nice-dcv-ubuntu2204-x86_64.tgz',
        '      cd nice-dcv-*-ubuntu2204-x86_64',
        '      sudo apt-get install -y ./nice-dcv-gl_*.deb || echo "DCV GL install warning"',
        '    fi',
        '  fi',
        '',
        '# ========== ROCKY/RHEL ==========',
        'elif [ "$DISTRO" = "rocky" ] || [ "$DISTRO" = "rhel" ] || [ "$DISTRO" = "centos" ]; then',
        '  # Determine el version for package URLs and CUDA repo',
        '  if [ "$MAJOR_VERSION" = "9" ]; then',
        '    EL_VERSION="el9"',
        '    CUDA_REPO="rhel9"',
        '  else',
        '    EL_VERSION="el8"',
        '    CUDA_REPO="rhel8"',
        '  fi',
        '  echo "Using package set: $EL_VERSION, CUDA repo: $CUDA_REPO"',
        '',
        '  if [ "$NVIDIA_INSTALLED" = "false" ]; then',
        '    echo "Installing EPEL repository (required for dkms)..."',
        '    sudo dnf install -y epel-release',
        '',
        '    echo "Installing kernel headers and development tools..."',
        '    sudo dnf install -y kernel-devel-$(uname -r) kernel-headers-$(uname -r)',
        '    sudo dnf install -y gcc make dkms',
        '',
        '    echo "Blacklisting nouveau driver..."',
        '    echo "blacklist nouveau" | sudo tee /etc/modprobe.d/blacklist-nouveau.conf',
        '    echo "options nouveau modeset=0" | sudo tee -a /etc/modprobe.d/blacklist-nouveau.conf',
        '    sudo dracut --force',
        '',
        '    echo "Installing NVIDIA drivers from CUDA repo ($CUDA_REPO)..."',
        '    sudo dnf config-manager --add-repo "https://developer.download.nvidia.com/compute/cuda/repos/${CUDA_REPO}/x86_64/cuda-${CUDA_REPO}.repo"',
        '    sudo dnf install -y nvidia-driver nvidia-driver-libs nvidia-driver-cuda nvidia-xconfig',
        '  fi',
        '',
        '  if [ "$DCV_GL_INSTALLED" = "false" ]; then',
        '    echo "Installing DCV GL..."',
        '    cd /tmp/nice-dcv-*-${EL_VERSION}-x86_64 2>/dev/null || cd /tmp',
        '    if [ -f nice-dcv-gl-*.rpm ]; then',
        '      sudo dnf install -y ./nice-dcv-gl-*.rpm || echo "DCV GL install warning"',
        '    else',
        '      wget -q "https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-${EL_VERSION}-x86_64.tgz"',
        '      tar -xzf nice-dcv-${EL_VERSION}-x86_64.tgz',
        '      cd nice-dcv-*-${EL_VERSION}-x86_64',
        '      sudo dnf install -y ./nice-dcv-gl-*.rpm || echo "DCV GL install warning"',
        '    fi',
        '  fi',
        '',
        'else',
        '  echo "ERROR: Unsupported distro for GPU setup: $DISTRO"',
        '  exit 1',
        'fi',
        '',
        '# ========== COMMON ==========',
        '# Only run nvidia-xconfig if drivers were just installed or xorg.conf is missing',
        'if [ "$NVIDIA_INSTALLED" = "false" ] || [ ! -f /etc/X11/xorg.conf ]; then',
        '  echo "Generating xorg.conf for NVIDIA GPU..."',
        '  sudo nvidia-xconfig --preserve-busid --enable-all-gpus',
        '',
        '  # Add Virtual screen size for higher resolution support (GPU-dependent)',
        '  sudo sed -i "s/Depth       24$/Depth       24\\n        Virtual     4096 2160/" /etc/X11/xorg.conf',
        'else',
        '  echo "xorg.conf already exists — skipping nvidia-xconfig"',
        'fi',
        '',
        'echo "Phase 2 complete - REBOOT REQUIRED"',
        'echo "REBOOT_REQUIRED=true" | sudo tee /tmp/reboot_status'
      ],
      timeoutSeconds: '900'
    }
  }]
};
