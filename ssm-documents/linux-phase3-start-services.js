module.exports = {
  schemaVersion: '2.2',
  description: 'Phase 3: Start DCV services (no session creation - app handles that, Ubuntu/Rocky)',
  mainSteps: [{
    action: 'aws:runShellScript',
    name: 'Phase3StartServices',
    inputs: {
      runCommand: [
        '#!/bin/bash',
        'set -e',
        '',
        'echo "=== Phase 3: Start Services ==="',
        '',
        '# Detect distro',
        'if [ -f /etc/os-release ]; then',
        '  . /etc/os-release',
        '  DISTRO=$ID',
        'else',
        '  DISTRO="unknown"',
        'fi',
        'echo "Detected distro: $DISTRO"',
        '',
        '# ========== DISTRO-SPECIFIC SETUP ==========',
        'if [ "$DISTRO" = "ubuntu" ]; then',
        '  DEFAULT_USER="ubuntu"',
        '  GDM_SERVICE="gdm3"',
        '  echo "Disabling Ubuntu welcome dialogs..."',
        '  sudo mkdir -p /etc/skel/.config',
        '  echo "yes" | sudo tee /etc/skel/.config/gnome-initial-setup-done',
        '  sudo -u ubuntu mkdir -p /home/ubuntu/.config 2>/dev/null || true',
        '  echo "yes" | sudo -u ubuntu tee /home/ubuntu/.config/gnome-initial-setup-done 2>/dev/null || true',
        '  sudo sed -i "s/Prompt=.*/Prompt=never/" /etc/update-manager/release-upgrades 2>/dev/null || true',
        '  sudo pro config set apt_news=false 2>/dev/null || true',
        '',
        'elif [ "$DISTRO" = "rocky" ] || [ "$DISTRO" = "rhel" ] || [ "$DISTRO" = "centos" ]; then',
        '  DEFAULT_USER="rocky"',
        '  GDM_SERVICE="gdm"',
        '  echo "Disabling GNOME initial setup..."',
        '  sudo mkdir -p /etc/skel/.config',
        '  echo "yes" | sudo tee /etc/skel/.config/gnome-initial-setup-done',
        '  if id rocky &>/dev/null; then',
        '    sudo -u rocky mkdir -p /home/rocky/.config 2>/dev/null || true',
        '    echo "yes" | sudo -u rocky tee /home/rocky/.config/gnome-initial-setup-done 2>/dev/null || true',
        '  fi',
        '',
        'else',
        '  echo "WARNING: Unknown distro, using defaults"',
        '  DEFAULT_USER="root"',
        '  GDM_SERVICE="gdm"',
        'fi',
        '',
        '# ========== DISABLE SCREEN LOCK AND AUTO-LOGOUT ==========',
        'echo "Disabling screen lock and auto-logout..."',
        '',
        '# Configure dconf for all users (system-wide)',
        'sudo mkdir -p /etc/dconf/db/local.d',
        'cat << DCONFEOF | sudo tee /etc/dconf/db/local.d/00-disable-lock',
        '[org/gnome/desktop/screensaver]',
        'lock-enabled=false',
        'idle-activation-enabled=false',
        '',
        '[org/gnome/desktop/session]',
        'idle-delay=uint32 0',
        '',
        '[org/gnome/desktop/lockdown]',
        'disable-lock-screen=true',
        '',
        '[org/gnome/settings-daemon/plugins/power]',
        'sleep-inactive-ac-timeout=0',
        'sleep-inactive-ac-type="nothing"',
        'idle-dim=false',
        'DCONFEOF',
        '',
        '# Enable desktop icons extension (Rocky/RHEL only - Ubuntu uses different extension)',
        'if [ "$DISTRO" = "rocky" ] || [ "$DISTRO" = "rhel" ] || [ "$DISTRO" = "centos" ]; then',
        '  cat << DESKTOPEOF | sudo tee /etc/dconf/db/local.d/01-desktop-icons',
        '[org/gnome/shell]',
        "enabled-extensions=['desktop-icons@csoriano']",
        'DESKTOPEOF',
        'fi',
        '',
        '# Lock these settings (prevent user override)',
        'sudo mkdir -p /etc/dconf/db/local.d/locks',
        'cat << LOCKEOF | sudo tee /etc/dconf/db/local.d/locks/00-disable-lock',
        '/org/gnome/desktop/screensaver/lock-enabled',
        '/org/gnome/desktop/screensaver/idle-activation-enabled',
        '/org/gnome/desktop/session/idle-delay',
        '/org/gnome/desktop/lockdown/disable-lock-screen',
        '/org/gnome/settings-daemon/plugins/power/sleep-inactive-ac-timeout',
        '/org/gnome/settings-daemon/plugins/power/idle-dim',
        'LOCKEOF',
        '',
        '# Update dconf database',
        'sudo dconf update',
        '',
        '# Add os-auto-lock=false to DCV config to prevent lock on disconnect',
        'if ! grep -q "os-auto-lock" /etc/dcv/dcv.conf; then',
        '  sudo sed -i "/\\[security\\]/a os-auto-lock = false" /etc/dcv/dcv.conf',
        'fi',
        '',
        '# ========== ROCKY/RHEL: FIREWALL AND GRAPHICAL TARGET ==========',
        'if [ "$DISTRO" = "rocky" ] || [ "$DISTRO" = "rhel" ] || [ "$DISTRO" = "centos" ]; then',
        '  echo "Opening firewall port 8443 for DCV..."',
        '  sudo firewall-cmd --permanent --add-port=8443/tcp || true',
        '  sudo firewall-cmd --permanent --add-port=8443/udp || true',
        '  sudo firewall-cmd --reload || true',
        '',
        '  echo "Setting graphical.target as default..."',
        '  sudo systemctl set-default graphical.target',
        'fi',
        '',
        '# ========== COMMON: GPU WAIT ==========',
        'if lspci | grep -qi nvidia; then',
        '  echo "Waiting for NVIDIA driver..."',
        '  for i in {1..30}; do',
        '    if nvidia-smi > /dev/null 2>&1; then',
        '      echo "NVIDIA driver ready"',
        '      nvidia-smi',
        '      break',
        '    fi',
        '    echo "Waiting... ($i/30)"',
        '    sleep 5',
        '  done',
        'fi',
        '',
        '# ========== CREATE AUTOLOGIN BOOT SERVICE ==========',
        '# This service ensures autologin works on every boot by restarting GDM',
        '# GDM autologin only triggers on GDM start, not when session ends, so we restart it',
        'echo "Creating autologin boot service..."',
        'cat << SERVICEEOF | sudo tee /etc/systemd/system/ensure-autologin.service',
        '[Unit]',
        'Description=Ensure GDM autologin on boot',
        'After=graphical.target $GDM_SERVICE.service',
        'Wants=graphical.target',
        '',
        '[Service]',
        'Type=oneshot',
        'RemainAfterExit=yes',
        'ExecStartPre=/bin/sleep 20',
        'ExecStart=/bin/bash -c "systemctl restart $GDM_SERVICE; sleep 15; pgrep -x Xorg || systemctl restart $GDM_SERVICE"',
        '',
        '[Install]',
        'WantedBy=graphical.target',
        'SERVICEEOF',
        '',
        '# Replace $GDM_SERVICE in the service file with actual value',
        'sudo sed -i "s/\\$GDM_SERVICE/$GDM_SERVICE/g" /etc/systemd/system/ensure-autologin.service',
        '',
        'sudo systemctl daemon-reload',
        'sudo systemctl enable ensure-autologin.service',
        '',
        '# ========== COMMON: START SERVICES ==========',
        '# Switch to graphical target (ensures X server runs properly for console sessions)',
        'echo "Switching to graphical target..."',
        'sudo systemctl isolate graphical.target || true',
        'sleep 5',
        '',
        'echo "Restarting GDM ($GDM_SERVICE) to apply autologin config..."',
        'sudo systemctl enable $GDM_SERVICE',
        'sudo systemctl restart $GDM_SERVICE',
        'sleep 10',
        '',
        '# Verify Xorg is running, retry if not',
        'echo "Verifying Xorg is running..."',
        'for i in {1..3}; do',
        '  if pgrep -x Xorg > /dev/null; then',
        '    echo "Xorg is running"',
        '    break',
        '  fi',
        '  echo "Xorg not running, restarting GDM (attempt $i/3)..."',
        '  sudo systemctl restart $GDM_SERVICE',
        '  sleep 10',
        'done',
        '',
        'echo "Starting DCV Server..."',
        'sudo systemctl enable dcvserver',
        'sudo systemctl start dcvserver',
        'sleep 3',
        '',
        'echo "Starting Session Manager Agent..."',
        'sudo systemctl enable dcv-session-manager-agent',
        'sudo systemctl start dcv-session-manager-agent',
        'sleep 5',
        '',
        '# ========== APPLY SETTINGS TO RUNNING SESSION ==========',
        '# The dconf database is system-wide, but we need to apply settings to the running session',
        '# Wait for user session to be fully established',
        'echo "Waiting for user session to be ready..."',
        'for i in {1..30}; do',
        '  if [ -S "/run/user/$(id -u $DEFAULT_USER)/bus" ]; then',
        '    echo "D-Bus session bus ready"',
        '    break',
        '  fi',
        '  echo "Waiting for D-Bus session... ($i/30)"',
        '  sleep 2',
        'done',
        '',
        'echo "Applying screen lock settings to running session..."',
        'USER_ID=$(id -u $DEFAULT_USER)',
        'export DBUS_SESSION_BUS_ADDRESS="unix:path=/run/user/$USER_ID/bus"',
        '',
        '# Apply gsettings to disable screen lock in the running session',
        'sudo -u $DEFAULT_USER DBUS_SESSION_BUS_ADDRESS="$DBUS_SESSION_BUS_ADDRESS" gsettings set org.gnome.desktop.screensaver lock-enabled false 2>/dev/null || true',
        'sudo -u $DEFAULT_USER DBUS_SESSION_BUS_ADDRESS="$DBUS_SESSION_BUS_ADDRESS" gsettings set org.gnome.desktop.screensaver idle-activation-enabled false 2>/dev/null || true',
        'sudo -u $DEFAULT_USER DBUS_SESSION_BUS_ADDRESS="$DBUS_SESSION_BUS_ADDRESS" gsettings set org.gnome.desktop.session idle-delay 0 2>/dev/null || true',
        'sudo -u $DEFAULT_USER DBUS_SESSION_BUS_ADDRESS="$DBUS_SESSION_BUS_ADDRESS" gsettings set org.gnome.desktop.lockdown disable-lock-screen true 2>/dev/null || true',
        'sudo -u $DEFAULT_USER DBUS_SESSION_BUS_ADDRESS="$DBUS_SESSION_BUS_ADDRESS" gsettings set org.gnome.settings-daemon.plugins.power sleep-inactive-ac-timeout 0 2>/dev/null || true',
        'sudo -u $DEFAULT_USER DBUS_SESSION_BUS_ADDRESS="$DBUS_SESSION_BUS_ADDRESS" gsettings set org.gnome.settings-daemon.plugins.power idle-dim false 2>/dev/null || true',
        '',
        '# Enable desktop icons extension (Rocky/RHEL only)',
        'if [ "$DISTRO" = "rocky" ] || [ "$DISTRO" = "rhel" ] || [ "$DISTRO" = "centos" ]; then',
        '  echo "Enabling desktop icons extension..."',
        "  sudo -u $DEFAULT_USER DBUS_SESSION_BUS_ADDRESS=\"$DBUS_SESSION_BUS_ADDRESS\" gsettings set org.gnome.shell enabled-extensions \"['desktop-icons@csoriano']\" 2>/dev/null || true",
        'fi',
        '',
        '# Verify settings were applied',
        'echo "Verifying screen lock settings..."',
        'LOCK_ENABLED=$(sudo -u $DEFAULT_USER DBUS_SESSION_BUS_ADDRESS="$DBUS_SESSION_BUS_ADDRESS" gsettings get org.gnome.desktop.screensaver lock-enabled 2>/dev/null || echo "unknown")',
        'echo "lock-enabled: $LOCK_ENABLED"',
        '',
        '# Status check',
        'echo "=== Service Status ==="',
        'systemctl status $GDM_SERVICE --no-pager || true',
        'systemctl status dcvserver --no-pager || true',
        'systemctl status dcv-session-manager-agent --no-pager || true',
        'pgrep -x Xorg && echo "Xorg: RUNNING" || echo "Xorg: NOT RUNNING"',
        '',
        'echo "Phase 3 complete!"'
      ],
      timeoutSeconds: '300'
    }
  }]
};
