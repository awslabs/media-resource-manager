module.exports = {
    schemaVersion: '2.2',
    description: 'Install DCV Server and Session Manager Agent on Windows workstations',
    parameters: {
        SessMgrDNS: {
            type: 'String',
            description: 'Session Manager DNS endpoint'
            // Removed default parameter - must be passed explicitly to avoid resolution issues
        }
    },
    mainSteps: [
        {
            action: 'aws:runPowerShellScript',
            name: 'InstallDCVandSMAgent',
            inputs: {
                runCommand: [
                    '# Get Session Manager DNS from parameter',
                    '$SessMgrDNS = "{{SessMgrDNS}}"',
                    '$BrokerAgentConnectionPort = "8445"',
                    '',
                    '# Get instance metadata',
                    '$token = Invoke-RestMethod -Headers @{\'X-aws-ec2-metadata-token-ttl-seconds\' = \'21600\'} -Method PUT -Uri http://169.254.169.254/latest/api/token -UseBasicParsing',
                    '$instanceType = Invoke-RestMethod -Headers @{\'X-aws-ec2-metadata-token\' = $token} -Method GET -Uri http://169.254.169.254/latest/meta-data/instance-type -UseBasicParsing',
                    '$OSVersion = ((Get-ItemProperty -Path "Microsoft.PowerShell.Core\\Registry::\\HKEY_LOCAL_MACHINE\\SOFTWARE\\Microsoft\\Windows NT\\CurrentVersion" -Name ProductName).ProductName) -replace "[^0-9]", \'\'',
                    '',
                    'if(($OSVersion -eq "2016") -and (($InstanceType[0] -ne \'g\') -or ($InstanceType[0] -ne \'p\'))){',
                    '    $VirtualDisplayDriverRequired = $true',
                    '}',
                    '',
                    '# Check and install Visual C++ prerequisite',
                    '$InstalledSoftware = (Get-ItemProperty -Path HKLM:\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\*) | Where-Object {$_.DisplayName -like "Microsoft Visual C++ 2022*"}',
                    'if($InstalledSoftware.count -eq 0){',
                    '    Write-Output "Installing Visual C++ Redistributable..."',
                    '    Start-Job -Name VcWebReq -ScriptBlock { Invoke-WebRequest -uri https://aka.ms/vs/17/release/vc_redist.x64.exe -OutFile C:\\Windows\\Temp\\vc_redist_64.exe -UseBasicParsing }',
                    '    Wait-Job -Name VcWebReq',
                    '    Invoke-Command -ScriptBlock { . C:\\Windows\\Temp\\vc_redist_64.exe /install /passive /norestart }',
                    '}',
                    '',
                    '# Wait for any existing MSI installations to complete (e.g., CrowdStrike, Tanium)',
                    'Write-Output "Checking for existing MSI installations..."',
                    '$maxWaitMinutes = 20',
                    '$waitedSeconds = 0',
                    '$checkIntervalSeconds = 15',
                    '',
                    'while ($waitedSeconds -lt ($maxWaitMinutes * 60)) {',
                    '    $activeInstalls = Get-WmiObject Win32_Process -Filter "Name=\'msiexec.exe\'" -ErrorAction SilentlyContinue | Where-Object { $_.CommandLine -match \'/[Ii]\\s\' }',
                    '    if (-not $activeInstalls) {',
                    '        Write-Output "No active MSI installations detected, proceeding with DCV install..."',
                    '        break',
                    '    }',
                    '    $waitedMinutes = [math]::Round($waitedSeconds / 60, 1)',
                    '    Write-Output "Waiting for existing MSI installation to complete... ($waitedMinutes min elapsed)"',
                    '    Start-Sleep -Seconds $checkIntervalSeconds',
                    '    $waitedSeconds += $checkIntervalSeconds',
                    '}',
                    '',
                    'if ($waitedSeconds -ge ($maxWaitMinutes * 60)) {',
                    '    Write-Output "WARNING: Timed out waiting for existing installations after $maxWaitMinutes minutes. Proceeding anyway..."',
                    '}',
                    '',
                    '# Download DCV packages',
                    'Write-Output "Downloading DCV packages..."',
                    'if($VirtualDisplayDriverRequired){',
                    '    Start-Job -Name WebReq -ScriptBlock {',
                    '        Invoke-WebRequest -uri https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-virtual-display-x64-Release.msi -OutFile C:\\Windows\\Temp\\DCVDisplayDriver.msi -UseBasicParsing',
                    '        Invoke-WebRequest -uri https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-server-x64-Release.msi -OutFile C:\\Windows\\Temp\\DCVServer.msi -UseBasicParsing',
                    '    }',
                    '}else{',
                    '    Start-Job -Name WebReq -ScriptBlock { Invoke-WebRequest -uri https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-server-x64-Release.msi -OutFile C:\\Windows\\Temp\\DCVServer.msi -UseBasicParsing }',
                    '}',
                    'Wait-Job -Name WebReq',
                    '',
                    '# Install DCV packages with retry on error 1618 (another installation in progress)',
                    'Write-Output "Installing DCV Server..."',
                    'if($VirtualDisplayDriverRequired){',
                    '    Invoke-Command -ScriptBlock {Start-Process "msiexec.exe" -ArgumentList "/I C:\\Windows\\Temp\\DCVDisplayDriver.msi /quiet /norestart" -Wait}',
                    '}',
                    '',
                    '$maxRetries = 20',
                    '$retryCount = 0',
                    '$installed = $false',
                    '',
                    'while (-not $installed -and $retryCount -lt $maxRetries) {',
                    '    Write-Output "Installing DCV Server (attempt $($retryCount + 1) of $maxRetries)..."',
                    '    $process = Start-Process "msiexec.exe" -ArgumentList "/I C:\\Windows\\Temp\\DCVServer.msi ADDLOCAL=ALL /quiet /norestart /l*v C:\\Windows\\Temp\\dcv_install_msi.log" -Wait -PassThru',
                    '    if ($process.ExitCode -eq 0) {',
                    '        $installed = $true',
                    '        Write-Output "DCV Server installed successfully"',
                    '    } elseif ($process.ExitCode -eq 1618) {',
                    '        $retryCount++',
                    '        Write-Output "Another installation in progress (error 1618), waiting 30 seconds before retry..."',
                    '        Start-Sleep -Seconds 30',
                    '    } elseif ($process.ExitCode -eq 3010) {',
                    '        $installed = $true',
                    '        Write-Output "DCV Server installed successfully (reboot may be required)"',
                    '    } elseif ($process.ExitCode -eq 1622) {',
                    '        # Error 1622: Transaction commit failed - but installation may have succeeded',
                    '        # This can happen when the MSI server process completes but client fails to close transaction',
                    '        Write-Output "MSI returned error 1622 (transaction commit failed), verifying installation..."',
                    '        Start-Sleep -Seconds 5',
                    '        $dcvProduct = Get-ItemProperty HKLM:\\Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\* -ErrorAction SilentlyContinue | Where-Object { $_.DisplayName -like \'*DCV Server*\' }',
                    '        if ($dcvProduct) {',
                    '            $installed = $true',
                    '            Write-Output "DCV Server verified installed (version: $($dcvProduct.DisplayVersion)) despite error 1622"',
                    '        } else {',
                    '            throw "DCV Server installation failed with exit code 1622 and product not found in registry"',
                    '        }',
                    '    } else {',
                    '        throw "DCV Server installation failed with exit code: $($process.ExitCode)"',
                    '    }',
                    '}',
                    '',
                    'if (-not $installed) {',
                    '    throw "DCV Server installation failed after $maxRetries attempts due to MSI mutex conflicts"',
                    '}',
                    '',
                    '# Wait for DCV service',
                    'Write-Output "Waiting for DCV service..."',
                    'while (-not(Get-Service dcvserver -ErrorAction SilentlyContinue)) { Start-Sleep -Milliseconds 250 }',
                    '',
                    '# Configure DCV',
                    'Write-Output "Configuring DCV Server..."',
                    '$dcvPath = "Microsoft.PowerShell.Core\\Registry::\\HKEY_USERS\\S-1-5-18\\Software\\GSettings\\com\\nicesoftware\\dcv"',
                    'Set-ItemProperty -Path "$dcvPath\\session-management" -Name create-session -Value 0 -force',
                    'New-ItemProperty -Path "$dcvPath\\security" -Name "auth-token-verifier" -Value "https://$SessMgrDNS`:$BrokerAgentConnectionPort/agent/validate-authentication-token" -Force',
                    'New-ItemProperty -Path "$dcvPath\\security" -Name no-tls-strict -PropertyType DWORD -Value 1 -force',
                    'Stop-Service dcvserver',
                    '',
                    '# Download and install Session Manager Agent',
                    'Write-Output "Installing Session Manager Agent..."',
                    'Start-Job -Name SMWebReq -ScriptBlock { Invoke-WebRequest -uri https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-session-manager-agent-x64-Release.msi -OutFile C:\\Windows\\Temp\\DCVSMAgent.msi -UseBasicParsing }',
                    'Wait-Job -Name SMWebReq',
                    'Invoke-Command -ScriptBlock {Start-Process "msiexec.exe" -ArgumentList "/I C:\\Windows\\Temp\\DCVSMAgent.msi /quiet /norestart" -Wait}',
                    '',
                    '# Wait for SM Agent service',
                    'Write-Output "Waiting for Session Manager Agent service..."',
                    'while (-not(Get-Service DcvSessionManagerAgentService -ErrorAction SilentlyContinue)) { Start-Sleep -Milliseconds 250 }',
                    'Stop-Service DcvSessionManagerAgentService',
                    '',
                    '# Configure Session Manager Agent',
                    'Write-Output "Configuring Session Manager Agent..."',
                    '$AgentConfContent = @"',
                    'version = \'0.1\'',
                    '[agent]',
                    'broker_host = \'$SessMgrDNS\'',
                    'broker_port = $BrokerAgentConnectionPort',
                    'tls_strict = false',
                    'broker_update_interval = 15',
                    '[log]',
                    'level = \'debug\'',
                    'rotation = \'daily\'',
                    '"@',
                    '',
                    '$AgentConfFolder = "C:\\Program Files\\NICE\\DCVSessionManagerAgent\\conf"',
                    'New-Item -Path $AgentConfFolder -Name "agent.conf" -ItemType File -Force -Value $AgentConfContent',
                    '',
                    '# Start services',
                    'Write-Output "Starting DCV and Session Manager services..."',
                    'Set-Service -Name DcvSessionManagerAgentService -StartupType Automatic',
                    'Start-Service dcvserver',
                    'Start-Service DcvSessionManagerAgentService',
                    '',
                    'Write-Output "DCV and Session Manager Agent installation completed successfully!"'
                ]
            }
        }
    ]
};
