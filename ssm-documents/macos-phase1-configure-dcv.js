// Source: lib/workstation-creation-stack-macos.ts lines 84-186
// Copy the content object from the CfnDocument definition

module.exports = {
  schemaVersion: '2.2',
  description: 'Phase 1: Configure DCV Server and Session Manager Agent on macOS',
  parameters: {
    SessMgrDNS: { type: 'String', description: 'Session Manager DNS endpoint' },
    BrokerPort: { type: 'String', default: '8445', description: 'Broker port' }
  },
  mainSteps: [{
    action: 'aws:runShellScript',
    name: 'ConfigureDCV',
    inputs: {
      runCommand: [
        '#!/bin/bash',
        'set -e',
        'SESS_MGR_DNS="{{SessMgrDNS}}"',
        'BROKER_PORT="{{BrokerPort}}"',
        '',
        'echo "=== Phase 1: Configure DCV on macOS ==="',
        'echo "Session Manager DNS: $SESS_MGR_DNS"',
        'echo "Broker Port: $BROKER_PORT"',
        '',
        '# Check if DCV Server is installed',
        'if [ ! -d "/Applications/DCV Server.app" ]; then',
        '  echo "DCV Server not found, attempting to install..."',
        '  cd /tmp',
        '  # Detect architecture',
        '  ARCH=$(uname -m)',
        '  if [ "$ARCH" = "arm64" ]; then',
        '    curl -O https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-server-macos-arm64.dist.pkg',
        '    sudo installer -pkg nice-dcv-server-macos-arm64.dist.pkg -target /',
        '  else',
        '    curl -O https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-server-macos-x86_64.dist.pkg',
        '    sudo installer -pkg nice-dcv-server-macos-x86_64.dist.pkg -target /',
        '  fi',
        'fi',
        '',
        '# Download and install Session Manager Agent if not present',
        'if [ ! -f "/Library/LaunchDaemons/com.amazon.dcv.session-manager.agent.plist" ]; then',
        '  echo "Installing DCV Session Manager Agent..."',
        '  cd /tmp',
        '  ARCH=$(uname -m)',
        '  if [ "$ARCH" = "arm64" ]; then',
        '    curl -O https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-session-manager-agent-macos-arm64.pkg',
        '    sudo installer -pkg nice-dcv-session-manager-agent-macos-arm64.pkg -target /',
        '  else',
        '    curl -O https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-session-manager-agent-macos-x86_64.pkg',
        '    sudo installer -pkg nice-dcv-session-manager-agent-macos-x86_64.pkg -target /',
        '  fi',
        'fi',
        '',
        '# Configure Session Manager Agent - write to the correct macOS location',
        'echo "Configuring Session Manager Agent..."',
        'AGENT_CONF_DIR="/Applications/DCV Session Manager Agent.app/Contents/Resources/etc"',
        'sudo mkdir -p "$AGENT_CONF_DIR"',
        'sudo tee "$AGENT_CONF_DIR/agent.conf" > /dev/null << AGENTEOF',
        "version = '0.1'",
        '[agent]',
        "broker_host = '${SESS_MGR_DNS}'",
        'broker_port = ${BROKER_PORT}',
        'tls_strict = false',
        'broker_update_interval = 15',
        '[log]',
        "level = 'debug'",
        "rotation = 'daily'",
        'AGENTEOF',
        '',
        '# Also create symlink/copy to /etc location for compatibility',
        'sudo mkdir -p /etc/dcv-session-manager-agent',
        'sudo cp "$AGENT_CONF_DIR/agent.conf" /etc/dcv-session-manager-agent/agent.conf',
        '',
        '# Configure DCV Server - write to the correct macOS location',
        'echo "Configuring DCV Server..."',
        'DCV_CONF_DIR="/Applications/DCV Server.app/Contents/Resources/etc"',
        'sudo mkdir -p "$DCV_CONF_DIR"',
        'sudo tee "$DCV_CONF_DIR/dcv.conf" > /dev/null << DCVEOF',
        '[license]',
        '[log]',
        'level = "debug"',
        '[session-management]',
        'create-session = false',
        '[session-management/automatic-console-session]',
        '[display]',
        'enable-client-resize = true',
        '[connectivity]',
        '[security]',
        'administrators = ["dcvsmagent"]',
        'auth-token-verifier = "https://${SESS_MGR_DNS}:${BROKER_PORT}/agent/validate-authentication-token"',
        'no-tls-strict = true',
        'os-auto-lock = false',
        '[clipboard]',
        'primary-selection-copy = true',
        'primary-selection-paste = true',
        'DCVEOF',
        '',
        '# Also create symlink/copy to /etc location for compatibility',
        'sudo mkdir -p /etc/dcv',
        'sudo cp "$DCV_CONF_DIR/dcv.conf" /etc/dcv/dcv.conf',
        '',
        '# Start/restart services',
        'echo "Starting DCV services..."',
        'sudo launchctl unload /Library/LaunchDaemons/com.amazon.dcv.server.dcvserver.plist 2>/dev/null || true',
        'sleep 2',
        'sudo launchctl load /Library/LaunchDaemons/com.amazon.dcv.server.dcvserver.plist',
        '',
        'sudo launchctl unload /Library/LaunchDaemons/com.amazon.dcv.session-manager.agent.plist 2>/dev/null || true',
        'sleep 2',
        'sudo launchctl load /Library/LaunchDaemons/com.amazon.dcv.session-manager.agent.plist',
        '',
        'sleep 5',
        'echo "Phase 1 complete!"',
        'echo "Agent config written to: $AGENT_CONF_DIR/agent.conf"',
        'echo "DCV config written to: $DCV_CONF_DIR/dcv.conf"'
      ],
      timeoutSeconds: '600'
    }
  }]
};
