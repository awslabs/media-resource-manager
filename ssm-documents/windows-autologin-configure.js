// SSM Document: Windows Auto-Login Configuration
// Configures Windows auto-login for standalone workstations using password from Secrets Manager
// Parameters:
//   - PascalCaseName: The pascal case name prefix for SSM parameters (e.g., TegnaFleetCommand)
//   - PrimaryRegion: The primary region where SSM parameters and secrets are stored (e.g., us-east-1)

module.exports = {
  schemaVersion: '2.2',
  description: 'Configure Windows auto-login for standalone workstations',
  parameters: {
    PascalCaseName: {
      type: 'String',
      description: 'Pascal case name prefix for SSM parameters'
    },
    PrimaryRegion: {
      type: 'String',
      description: 'Primary region where SSM parameters and secrets are stored'
    }
  },
  mainSteps: [
    {
      action: 'aws:runPowerShellScript',
      name: 'ConfigureAutoLogin',
      inputs: {
        runCommand: [
          '# Configure Windows Auto-Login for standalone workstations',
          'param(',
          '    [string]$PascalCaseName = "{{PascalCaseName}}",',
          '    [string]$PrimaryRegion = "{{PrimaryRegion}}"',
          ')',
          '',
          'Write-Host "Configuring Windows auto-login and session persistence for DCV access"',
          'Write-Host "PascalCaseName: $PascalCaseName"',
          'Write-Host "PrimaryRegion: $PrimaryRegion"',
          '',
          'try {',
          '    # === AUTO-LOGIN CONFIGURATION ===',
          '    $regPath = "HKLM:\\SOFTWARE\\Microsoft\\Windows NT\\CurrentVersion\\Winlogon"',
          '    Set-ItemProperty -Path $regPath -Name "AutoAdminLogon" -Value "1" -Type String -Force',
          '    Set-ItemProperty -Path $regPath -Name "ForceAutoLogon" -Value "1" -Type String -Force',
          '    Set-ItemProperty -Path $regPath -Name "DefaultUserName" -Value "Administrator" -Type String -Force',
          '    ',
          '    # SSM parameter and Secrets Manager secret are in primary region',
          '    Write-Host "Setting AWS region to primary region: $PrimaryRegion"',
          '    Set-DefaultAWSRegion -Region $PrimaryRegion',
          '    ',
          '    $secretArnParam = "/$PascalCaseName/Workstation/StandaloneAdminPasswordSecretArn"',
          '    Write-Host "Getting secret ARN from SSM parameter: $secretArnParam"',
          '    $secretArn = (Get-SSMParameter -Name $secretArnParam -Region $PrimaryRegion).Value',
          '    Write-Host "Retrieved secret ARN: $secretArn"',
          '    ',
          '    # Get the actual password from Secrets Manager (secret is in primary region)',
          '    $password = (Get-SECSecretValue -SecretId $secretArn -Region $PrimaryRegion).SecretString',
          '    ',
          '    Set-ItemProperty -Path $regPath -Name "DefaultPassword" -Value $password -Type String -Force',
          '    ',
          '    # Disable password expiration for Administrator',
          '    net user Administrator /expires:never 2>$null',
          '    ',
          '    # Set the Administrator password',
          '    net user Administrator $password 2>$null',
          '    ',
          '    Write-Host "Successfully configured auto-login for Administrator"',
          '    ',
          '    # === DISABLE IDLE DISCONNECT/SIGN-OUT ===',
          '    Write-Host "Disabling idle disconnect and auto sign-out..."',
          '    ',
          '    # Disable screen saver and lock screen',
          '    $screenSaverPath = "HKCU:\\Control Panel\\Desktop"',
          '    Set-ItemProperty -Path $screenSaverPath -Name "ScreenSaveActive" -Value "0" -Type String -Force -ErrorAction SilentlyContinue',
          '    Set-ItemProperty -Path $screenSaverPath -Name "ScreenSaverIsSecure" -Value "0" -Type String -Force -ErrorAction SilentlyContinue',
          '    Set-ItemProperty -Path $screenSaverPath -Name "ScreenSaveTimeOut" -Value "0" -Type String -Force -ErrorAction SilentlyContinue',
          '    ',
          '    # Disable lock screen via registry (machine-wide)',
          '    $personalizePath = "HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\Personalization"',
          '    if (!(Test-Path $personalizePath)) { New-Item -Path $personalizePath -Force | Out-Null }',
          '    Set-ItemProperty -Path $personalizePath -Name "NoLockScreen" -Value 1 -Type DWord -Force',
          '    ',
          '    # Disable idle disconnect via Local Security Policy (secpol)',
          '    # Set "Interactive logon: Machine inactivity limit" to 0 (disabled)',
          '    $securityPath = "HKLM:\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Policies\\System"',
          '    Set-ItemProperty -Path $securityPath -Name "InactivityTimeoutSecs" -Value 0 -Type DWord -Force',
          '    ',
          '    # Disable lock workstation functionality (Ctrl+L, Start menu lock)',
          '    $explorerPath = "HKLM:\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Policies\\Explorer"',
          '    if (!(Test-Path $explorerPath)) { New-Item -Path $explorerPath -Force | Out-Null }',
          '    Set-ItemProperty -Path $explorerPath -Name "NoLock" -Value 1 -Type DWord -Force',
          '    ',
          '    # Disable Ctrl+Alt+Del requirement',
          '    Set-ItemProperty -Path $securityPath -Name "DisableCAD" -Value 1 -Type DWord -Force',
          '    ',
          '    # Disable console lock display off timeout',
          '    $consoleLockPath = "HKLM:\\SYSTEM\\CurrentControlSet\\Control\\Power\\PowerSettings\\7516b95f-f776-4464-8c53-06167f40cc99\\8EC4B3A5-6868-48c2-BE75-4F3044BE88A7"',
          '    if (Test-Path $consoleLockPath) {',
          '        Set-ItemProperty -Path $consoleLockPath -Name "Attributes" -Value 2 -Type DWord -Force -ErrorAction SilentlyContinue',
          '    }',
          '    powercfg /setacvalueindex SCHEME_CURRENT SUB_VIDEO VIDEOCONLOCK 0 2>$null',
          '    powercfg /setdcvalueindex SCHEME_CURRENT SUB_VIDEO VIDEOCONLOCK 0 2>$null',
          '    powercfg /setactive SCHEME_CURRENT 2>$null',
          '    ',
          '    # Disable automatic lock after screen saver (additional protection)',
          '    $winlogonPath = "HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\Control Panel\\Desktop"',
          '    if (!(Test-Path $winlogonPath)) { New-Item -Path $winlogonPath -Force | Out-Null }',
          '    Set-ItemProperty -Path $winlogonPath -Name "ScreenSaverIsSecure" -Value "0" -Type String -Force',
          '    ',
          '    # Disable dynamic lock (locks when Bluetooth device goes out of range)',
          '    $dynamicLockPath = "HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\System"',
          '    if (!(Test-Path $dynamicLockPath)) { New-Item -Path $dynamicLockPath -Force | Out-Null }',
          '    Set-ItemProperty -Path $dynamicLockPath -Name "AllowDomainPINLogon" -Value 0 -Type DWord -Force -ErrorAction SilentlyContinue',
          '    ',
          '    # Disable lock on resume from sleep',
          '    $powerPoliciesPath = "HKLM:\\SOFTWARE\\Policies\\Microsoft\\Power\\PowerSettings\\0e796bdb-100d-47d6-a2d5-f7d2daa51f51"',
          '    if (!(Test-Path $powerPoliciesPath)) { New-Item -Path $powerPoliciesPath -Force | Out-Null }',
          '    Set-ItemProperty -Path $powerPoliciesPath -Name "ACSettingIndex" -Value 0 -Type DWord -Force',
          '    Set-ItemProperty -Path $powerPoliciesPath -Name "DCSettingIndex" -Value 0 -Type DWord -Force',
          '    ',
          '    # Disable Remote Desktop idle disconnect',
          '    $rdpTcpPath = "HKLM:\\SYSTEM\\CurrentControlSet\\Control\\Terminal Server\\WinStations\\RDP-Tcp"',
          '    Set-ItemProperty -Path $rdpTcpPath -Name "MaxIdleTime" -Value 0 -Type DWord -Force -ErrorAction SilentlyContinue',
          '    Set-ItemProperty -Path $rdpTcpPath -Name "MaxDisconnectionTime" -Value 0 -Type DWord -Force -ErrorAction SilentlyContinue',
          '    ',
          '    # === DCV SERVER CONFIGURATION ===',
          '    # DCV Server runs as SYSTEM (S-1-5-18), so settings must be in HKU\\S-1-5-18',
          '    # Mount HKU if not already available',
          '    if (!(Test-Path "HKU:")) { New-PSDrive -Name HKU -PSProvider Registry -Root HKEY_USERS | Out-Null }',
          '    ',
          '    # DCV security settings - disable OS auto-lock when last client disconnects',
          '    $dcvSecurityPath = "HKU:\\S-1-5-18\\Software\\GSettings\\com\\nicesoftware\\dcv\\security"',
          '    if (!(Test-Path $dcvSecurityPath)) { New-Item -Path $dcvSecurityPath -Force | Out-Null }',
          '    Set-ItemProperty -Path $dcvSecurityPath -Name "os-auto-lock" -Value 0 -Type DWord -Force',
          '    Write-Host "Set os-auto-lock=0 in HKU\\S-1-5-18"',
          '    ',
          '    # DCV connectivity settings - disable disconnect on lock',
          '    $dcvConnPath = "HKU:\\S-1-5-18\\Software\\GSettings\\com\\nicesoftware\\dcv\\connectivity"',
          '    if (!(Test-Path $dcvConnPath)) { New-Item -Path $dcvConnPath -Force | Out-Null }',
          '    Set-ItemProperty -Path $dcvConnPath -Name "disconnect-on-lock" -Value 0 -Type DWord -Force',
          '    Set-ItemProperty -Path $dcvConnPath -Name "idle-timeout" -Value 0 -Type DWord -Force',
          '    Write-Host "Set disconnect-on-lock=0 and idle-timeout=0 in connectivity"',
          '    ',
          '    # DCV session-management settings',
          '    $dcvSessionPath = "HKU:\\S-1-5-18\\Software\\GSettings\\com\\nicesoftware\\dcv\\session-management"',
          '    if (!(Test-Path $dcvSessionPath)) { New-Item -Path $dcvSessionPath -Force | Out-Null }',
          '    Set-ItemProperty -Path $dcvSessionPath -Name "disconnect-on-lock" -Value 0 -Type DWord -Force',
          '    ',
          '    # DCV automatic-console-session settings',
          '    $dcvAutoConsolePath = "HKU:\\S-1-5-18\\Software\\GSettings\\com\\nicesoftware\\dcv\\session-management\\automatic-console-session"',
          '    if (!(Test-Path $dcvAutoConsolePath)) { New-Item -Path $dcvAutoConsolePath -Force | Out-Null }',
          '    Set-ItemProperty -Path $dcvAutoConsolePath -Name "idle-timeout" -Value 0 -Type DWord -Force',
          '    ',
          '    Write-Host "DCV Server registry settings configured in HKU\\S-1-5-18"',
          '    ',
          '    # Disable power management sleep/hibernate',
          '    powercfg /change standby-timeout-ac 0',
          '    powercfg /change standby-timeout-dc 0',
          '    powercfg /change hibernate-timeout-ac 0',
          '    powercfg /change hibernate-timeout-dc 0',
          '    powercfg /change monitor-timeout-ac 0',
          '    powercfg /change monitor-timeout-dc 0',
          '    ',
          '    Write-Host "Disabled idle disconnect and auto sign-out settings"',
          '    ',
          '    # === VERIFICATION ===',
          '    $autoLogon = Get-ItemProperty -Path $regPath -Name "AutoAdminLogon" -ErrorAction SilentlyContinue',
          '    $forceLogon = Get-ItemProperty -Path $regPath -Name "ForceAutoLogon" -ErrorAction SilentlyContinue',
          '    $defaultUser = Get-ItemProperty -Path $regPath -Name "DefaultUserName" -ErrorAction SilentlyContinue',
          '    if ($autoLogon.AutoAdminLogon -eq "1" -and $forceLogon.ForceAutoLogon -eq "1" -and $defaultUser.DefaultUserName -eq "Administrator") {',
          '        Write-Host "Verification: Auto-login is configured correctly (AutoAdminLogon=1, ForceAutoLogon=1)"',
          '    } else {',
          '        Write-Host "Warning: Auto-login verification failed"',
          '    }',
          '} catch {',
          '    Write-Host "Error configuring auto-login: $($_.Exception.Message)"',
          '    exit 1',
          '}'
        ]
      }
    }
  ]
};
