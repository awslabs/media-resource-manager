module.exports = {
  schemaVersion: '2.2',
  description: 'Phase 1: Install desktop environment, DCV Server, and Session Manager Agent (Ubuntu/Rocky)',
  parameters: {
    SessMgrDNS: { type: 'String', description: 'Session Manager DNS endpoint' },
    AdminPasswordSecretArn: { type: 'String', description: 'Secrets Manager ARN for admin password' }
  },
  mainSteps: [{
    action: 'aws:runShellScript',
    name: 'Phase1BaseInstall',
    inputs: {
      runCommand: [
        '#!/bin/bash',
        'set -e',
        'SESS_MGR_DNS="{{SessMgrDNS}}"',
        'ADMIN_PASSWORD_SECRET_ARN="{{AdminPasswordSecretArn}}"',
        'BROKER_AGENT_PORT="8445"',
        '',
        'echo "=== Phase 1: Base Install ==="',
        '',
        '# Detect distro',
        'if [ -f /etc/os-release ]; then',
        '  . /etc/os-release',
        '  DISTRO=$ID',
        'else',
        '  DISTRO="unknown"',
        'fi',
        'echo "Detected distro: $DISTRO"',
        '',
        '# ========== SET USER PASSWORD ==========',
        '# Get password from Secrets Manager and set for default user',
        'echo "Setting up user password..."',
        'REGION=$(curl -s http://169.254.169.254/latest/meta-data/placement/region)',
        'ADMIN_PASSWORD=$(aws secretsmanager get-secret-value --secret-id "$ADMIN_PASSWORD_SECRET_ARN" --region "$REGION" --query SecretString --output text 2>/dev/null || echo "")',
        '',
        'if [ -n "$ADMIN_PASSWORD" ]; then',
        '  if [ "$DISTRO" = "ubuntu" ]; then',
        '    echo "Setting password for ubuntu user..."',
        '    echo "ubuntu:$ADMIN_PASSWORD" | sudo chpasswd',
        '  elif [ "$DISTRO" = "rocky" ] || [ "$DISTRO" = "rhel" ] || [ "$DISTRO" = "centos" ]; then',
        '    echo "Setting password for rocky user..."',
        '    # Create rocky user if it does not exist',
        '    if ! id rocky &>/dev/null; then',
        '      sudo useradd -m -s /bin/bash rocky',
        '      sudo usermod -aG wheel rocky',
        '    fi',
        '    echo "rocky:$ADMIN_PASSWORD" | sudo chpasswd',
        '  fi',
        '  echo "User password set successfully"',
        'else',
        '  echo "WARNING: Could not retrieve password from Secrets Manager"',
        'fi',
        '',
        '# Detect major version for package selection (el8 vs el9)',
        'MAJOR_VERSION=$(echo "$VERSION_ID" | cut -d. -f1)',
        'echo "Detected major version: $MAJOR_VERSION"',
        '',
        '# Check if DCV Server is already installed',
        'DCV_INSTALLED=false',
        'if command -v dcvserver &>/dev/null || systemctl list-unit-files dcvserver.service &>/dev/null 2>&1; then',
        '  DCV_INSTALLED=true',
        '  echo "DCV Server already installed — skipping DCV installation"',
        'fi',
        '',
        '# Check if DCV Session Manager Agent is already installed',
        'SM_AGENT_INSTALLED=false',
        'if command -v dcv-session-manager-agent &>/dev/null || systemctl list-unit-files dcv-session-manager-agent.service &>/dev/null 2>&1; then',
        '  SM_AGENT_INSTALLED=true',
        '  echo "DCV Session Manager Agent already installed — skipping agent installation"',
        'fi',
        '',
        '# ========== UBUNTU ==========',
        'if [ "$DISTRO" = "ubuntu" ]; then',
        '  export DEBIAN_FRONTEND=noninteractive',
        '  echo "Installing prerequisites (Ubuntu)..."',
        '  sudo apt-get update -y',
        '  sudo apt-get install -y wget gnupg2 software-properties-common',
        '',
        '  # Install desktop environment if not present',
        '  if ! dpkg -l | grep -q ubuntu-desktop-minimal; then',
        '    echo "Installing Ubuntu desktop environment..."',
        '    sudo apt-get install -y ubuntu-desktop-minimal gdm3',
        '  else',
        '    echo "Ubuntu desktop already installed — skipping"',
        '  fi',
        '',
        '  echo "Configuring GDM..."',
        '  sudo mkdir -p /etc/gdm3',
        '  cat << GDMEOF | sudo tee /etc/gdm3/custom.conf',
        '[daemon]',
        'WaylandEnable=false',
        'AutomaticLoginEnable=true',
        'AutomaticLogin=ubuntu',
        '[security]',
        '[xdmcp]',
        '[chooser]',
        '[debug]',
        'GDMEOF',
        '',
        '  if [ "$DCV_INSTALLED" = "false" ]; then',
        '    echo "Downloading DCV packages (Ubuntu)..."',
        '    cd /tmp',
        '    wget -q https://d1uj6qtbmh3dt5.cloudfront.net/NICE-GPG-KEY',
        '    gpg --import NICE-GPG-KEY || true',
        '    sudo cp NICE-GPG-KEY /etc/apt/trusted.gpg.d/nice-gpg-key.asc',
        '    wget -q https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-ubuntu2204-x86_64.tgz',
        '    tar -xzf nice-dcv-ubuntu2204-x86_64.tgz',
        '    cd nice-dcv-*-ubuntu2204-x86_64',
        '',
        '    echo "Installing DCV Server..."',
        '    sudo apt-get install -y ./nice-dcv-server_*.deb',
        '    sudo apt-get install -y ./nice-dcv-web-viewer_*.deb || true',
        '    sudo apt-get install -y ./nice-xdcv_*.deb || true',
        '  fi',
        '',
        '  if [ "$SM_AGENT_INSTALLED" = "false" ]; then',
        '    echo "Installing DCV Session Manager Agent..."',
        '    cd /tmp',
        '    wget -q https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-session-manager-agent_amd64.ubuntu2204.deb',
        '    sudo apt-get install -y ./nice-dcv-session-manager-agent_amd64.ubuntu2204.deb',
        '  fi',
        '',
        '# ========== ROCKY/RHEL ==========',
        'elif [ "$DISTRO" = "rocky" ] || [ "$DISTRO" = "rhel" ] || [ "$DISTRO" = "centos" ]; then',
        '  # Determine el version for package URLs',
        '  if [ "$MAJOR_VERSION" = "9" ]; then',
        '    EL_VERSION="el9"',
        '  else',
        '    EL_VERSION="el8"',
        '  fi',
        '  echo "Using package set: $EL_VERSION"',
        '',
        '  echo "Installing prerequisites (Rocky/RHEL)..."',
        '  sudo dnf install -y wget tar',
        '',
        '  # Install desktop environment if not present',
        '  if ! dnf group list installed 2>/dev/null | grep -qi "Server with GUI"; then',
        '    # Check if a desktop is already available (gdm or another display manager)',
        '    if command -v gdm &>/dev/null || command -v lightdm &>/dev/null || systemctl list-unit-files gdm.service &>/dev/null 2>&1; then',
        '      echo "Desktop environment already available — skipping group install"',
        '    else',
        '      echo "Installing Server with GUI group..."',
        '      sudo dnf groupinstall -y --allowerasing "Server with GUI" || {',
        '        echo "WARNING: Server with GUI group install failed, trying minimal desktop..."',
        '        sudo dnf install -y --allowerasing gdm gnome-session gnome-terminal gnome-shell || echo "WARNING: Desktop install failed — continuing anyway"',
        '      }',
        '    fi',
        '  else',
        '    echo "Server with GUI already installed — skipping"',
        '  fi',
        '  sudo dnf install -y --allowerasing gdm gnome-session gnome-terminal || true',
        '',
        '  echo "Configuring GDM..."',
        '  sudo mkdir -p /etc/gdm',
        '  cat << GDMEOF | sudo tee /etc/gdm/custom.conf',
        '[daemon]',
        'WaylandEnable=false',
        'AutomaticLoginEnable=true',
        'AutomaticLogin=rocky',
        '[security]',
        '[xdmcp]',
        '[chooser]',
        '[debug]',
        'GDMEOF',
        '',
        '  if [ "$DCV_INSTALLED" = "false" ]; then',
        '    echo "Downloading DCV packages (RHEL/Rocky $EL_VERSION)..."',
        '    cd /tmp',
        '    sudo rpm --import https://d1uj6qtbmh3dt5.cloudfront.net/NICE-GPG-KEY',
        '    wget -q "https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-${EL_VERSION}-x86_64.tgz"',
        '    tar -xzf nice-dcv-${EL_VERSION}-x86_64.tgz',
        '    cd nice-dcv-*-${EL_VERSION}-x86_64',
        '',
        '    echo "Installing DCV Server..."',
        '    sudo dnf install -y ./nice-dcv-server-*.rpm',
        '    sudo dnf install -y ./nice-dcv-web-viewer-*.rpm || true',
        '    sudo dnf install -y ./nice-xdcv-*.rpm || true',
        '  fi',
        '',
        '  if [ "$SM_AGENT_INSTALLED" = "false" ]; then',
        '    echo "Installing DCV Session Manager Agent..."',
        '    cd /tmp',
        '    wget -q "https://d1uj6qtbmh3dt5.cloudfront.net/nice-dcv-session-manager-agent-${EL_VERSION}.x86_64.rpm"',
        '    sudo dnf install -y ./nice-dcv-session-manager-agent-${EL_VERSION}.x86_64.rpm',
        '  fi',
        '',
        'else',
        '  echo "ERROR: Unsupported distro: $DISTRO"',
        '  exit 1',
        'fi',
        '',
        '# ========== COMMON CONFIG ==========',
        '# Set default user based on distro (for DCV session owner)',
        'if [ "$DISTRO" = "ubuntu" ]; then',
        '  DEFAULT_USER="ubuntu"',
        'elif [ "$DISTRO" = "rocky" ] || [ "$DISTRO" = "rhel" ] || [ "$DISTRO" = "centos" ]; then',
        '  DEFAULT_USER="rocky"',
        'else',
        '  DEFAULT_USER="root"',
        'fi',
        '',
        'echo "Configuring DCV Server..."',
        'sudo mkdir -p /etc/dcv',
        'cat << DCVEOF | sudo tee /etc/dcv/dcv.conf',
        '[license]',
        '[log]',
        'level = "debug"',
        '[session-management]',
        'create-session = false',
        '[session-management/automatic-console-session]',
        '[display]',
        'enable-client-resize = true',
        '[connectivity]',
        '[security]',
        'administrators = ["dcvsmagent"]',
        'auth-token-verifier = "https://${SESS_MGR_DNS}:${BROKER_AGENT_PORT}/agent/validate-authentication-token"',
        'no-tls-strict = true',
        '[clipboard]',
        'primary-selection-copy = true',
        'primary-selection-paste = true',
        'DCVEOF',
        '',
        'echo "Configuring Session Manager Agent..."',
        'sudo mkdir -p /etc/dcv-session-manager-agent',
        'cat << AGENTEOF | sudo tee /etc/dcv-session-manager-agent/agent.conf',
        "version = '0.1'",
        '[agent]',
        "broker_host = '${SESS_MGR_DNS}'",
        'broker_port = ${BROKER_AGENT_PORT}',
        'tls_strict = false',
        'broker_update_interval = 15',
        '[log]',
        "level = 'debug'",
        "rotation = 'daily'",
        'AGENTEOF',
        '',
        '# Check for GPU',
        'if lspci | grep -qi nvidia; then',
        '  echo "GPU_DETECTED=true" | sudo tee /tmp/gpu_status',
        '  echo "NVIDIA GPU detected"',
        'else',
        '  echo "GPU_DETECTED=false" | sudo tee /tmp/gpu_status',
        '  echo "No GPU detected"',
        'fi',
        '',
        'echo "Phase 1 complete!"'
      ],
      timeoutSeconds: '1200'
    }
  }]
};
