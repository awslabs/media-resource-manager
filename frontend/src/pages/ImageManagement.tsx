  // Validate AMI ID format (ami-xxxxxxxxxxxxxxxxx)
  const isValidAmiId = (amiId: string): boolean => {
    return /^ami-[a-f0-9]{8,17}$/.test(amiId);
  };

  const handleCreateImage = async () => {
    // Validate AMI ID format
    if (!isValidAmiId(formData.amiId)) {
      setAlert({ 
        type: 'error', 
        message: 'Invalid AMI ID format. AMI IDs must start with "ami-" followed by 8-17 hexadecimal characters (e.g., ami-0123456789abcdef0)' 
      });
      return;
    }

    try {
      const token = getAuthToken();
      if (!token) throw new Error('No current user');
      
      const response = await apiCall('images', {
        method: 'POST',
        headers: { 
          'Authorization': `Bearer ${token}`,
          'Content-Type': 'application/json'
        },
        body: JSON.stringify(formData)
      });
      
      if (!response.ok) {
        const errorText = await response.text();
        throw new Error(`API Error: ${response.status} - ${errorText}`);
      }
      
      setAlert({ type: 'success', message: 'Image created successfully' });
      setShowCreateModal(false);
      setFormData({ amiId: '', name: '', platform: '', description: '' });
      fetchData();
    } catch (error) {
      console.error('Error creating image:', error);
      setAlert({ type: 'error', message: `Failed to create image: ${error.message}` });
    }
  };

  const handleUpdateImage = async () => {
    if (!editingImage) return;
    
    try {
      const token = getAuthToken();
      if (!token) throw new Error('No current user');
      
      await apiCall(`images/${editingImage.amiId}`, {
        method: 'PUT',
        headers: { 
          'Authorization': `Bearer ${token}`,
          'Content-Type': 'application/json'
        },
        body: JSON.stringify({
          name: formData.name,
          platform: formData.platform,
          description: formData.description
        })
      });
      setAlert({ type: 'success', message: 'Image updated successfully' });
      setShowEditModal(false);
      setEditingImage(null);
      fetchData();
    } catch (error) {
      console.error('Error updating image:', error);
      setAlert({ type: 'error', message: 'Failed to update image' });
    }
  };

  const deletePipeline = async () => {
    if (selectedPipelines.length === 0) return;
    
    setDeleting(true);
    try {
      const token = getAuthToken();
      
      // Delete multiple pipelines
      await Promise.all(selectedPipelines.map(pipeline => 
        apiCall(`/images/pipelines/${pipeline.pipelineId}`, {
          method: 'DELETE',
          headers: { 'Authorization': `Bearer ${token}` }
        })
      ));

      setAlert({ 
        type: 'success', 
        message: `${selectedPipelines.length} pipeline(s) deleted successfully` 
      });
      setSelectedPipelines([]);
      setShowDeletePipelineModal(false);
      fetchPipelines();
    } catch (error) {
      console.error('Error deleting pipelines:', error);
      setAlert({ type: 'error', message: 'Failed to delete pipeline(s)' });
    } finally {
      setDeleting(false);
    }
  };

