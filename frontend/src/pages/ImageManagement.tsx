// Grouped image for display - represents a pipeline output or standalone image
interface GroupedImage {
  id: string; // pipelineId or amiId for standalone
  name: string;
  platform: string;
  description?: string;
  state?: string;
  createdAt?: string;
  isAutoGenerated?: boolean;
  requiresPipeline?: boolean;
  pipelineId?: string;
  // Computed type for filtering: 'Base Image', 'Pipeline', or 'Imported'
  type: string;
  // For grouped images, this contains all regional AMIs
  regions: Array<{
    region: string;
    amiId: string;
  }>;
  // For standalone images (no pipelineId), this is the single AMI
  amiId?: string;
  region?: string;
}

interface ImagePipeline {
  pipelineId: string;
  name: string;
  description?: string;
  status: 'CREATED' | 'BUILDING' | 'COMPLETED' | 'FAILED';
  baseImageId: string;
  baseOsVersion?: string; // e.g., "Windows Server 2022", "Windows Server 2019", "Ubuntu 20.04"
  components: PipelineComponent[];
  createdAt: string;
  updatedAt: string;
  pipelineArn: string;
  isSystemPipeline?: boolean; // System pipelines cannot be deleted
}

interface PipelineComponent {
  name: string;
  componentArn: string;
  type?: string;
}

interface SoftwareComponent {
  componentId: string;
  name: string;
  componentArn: string;
  componentVersion?: string;
  versionNumber?: string;
}

