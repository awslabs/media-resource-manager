// Base images for image pipelines. Used by the create wizard and by the
// "Change base image" picker in Edit pipeline.

export interface BaseImage {
  id: string;
  name: string;
  platform: string;
  description?: string;
  createdAt?: string;
  isAutoGenerated?: boolean;
}

// Built-in bases. The backend resolves each ID to the latest AWS AMI for that
// version whenever a pipeline is created, edited, or built, so every entry is
// "latest". Descriptions give the vendor's security support end date instead.
// Sources: Microsoft lifecycle (Windows Server), Canonical release cycle
// (Ubuntu standard security maintenance), Rocky Linux release notes. DaVinci
// Resolve 21.1 lists Rocky Linux 8.6 as its only supported Linux.
export const BUILT_IN_BASE_IMAGES: BaseImage[] = [
  { id: 'windows-2025', name: 'Windows Server 2025 Base', platform: 'Windows', description: 'Security updates until November 2034', isAutoGenerated: true },
  { id: 'windows-2022', name: 'Windows Server 2022 Base', platform: 'Windows', description: 'Security updates until October 2031', isAutoGenerated: true },
  { id: 'windows-2019', name: 'Windows Server 2019 Base', platform: 'Windows', description: 'Security updates until January 2029', isAutoGenerated: true },
  { id: 'ubuntu-22.04', name: 'Ubuntu Server 22.04 LTS', platform: 'Linux', description: 'Standard security updates until May 2027', isAutoGenerated: true },
  { id: 'rocky-8', name: 'Rocky Linux 8', platform: 'Linux', description: 'RHEL-compatible. Required for DaVinci Resolve. Security updates until May 2029', isAutoGenerated: true },
  { id: 'rocky-9', name: 'Rocky Linux 9', platform: 'Linux', description: 'RHEL-compatible. Security updates until May 2032', isAutoGenerated: true },
];

// macOS bases are images from the Images page: DCV-Ready images from the
// system pipeline, and golden images built from them.
export const toMacosBaseImages = (images: any[]): BaseImage[] =>
  (images || [])
    .filter((img) => img.platform?.toLowerCase() === 'macos')
    .map((img) => ({
      id: img.amiId,
      name: img.name,
      platform: 'macOS',
      description: img.description,
      createdAt: img.createdAt,
      isAutoGenerated: false,
    }));
